BEGIN;

ALTER TABLE public.crm_leads
  ADD COLUMN IF NOT EXISTS marketing_campaign_id text,
  ADD COLUMN IF NOT EXISTS attribution_session_id text,
  ADD COLUMN IF NOT EXISTS utm_source text,
  ADD COLUMN IF NOT EXISTS utm_medium text,
  ADD COLUMN IF NOT EXISTS utm_campaign text,
  ADD COLUMN IF NOT EXISTS utm_content text,
  ADD COLUMN IF NOT EXISTS utm_term text,
  ADD COLUMN IF NOT EXISTS gclid text,
  ADD COLUMN IF NOT EXISTS gbraid text,
  ADD COLUMN IF NOT EXISTS wbraid text,
  ADD COLUMN IF NOT EXISTS fbclid text,
  ADD COLUMN IF NOT EXISTS first_touch_at timestamptz,
  ADD COLUMN IF NOT EXISTS last_touch_at timestamptz;

CREATE INDEX IF NOT EXISTS idx_crm_leads_marketing_campaign
  ON public.crm_leads(marketing_campaign_id);
CREATE INDEX IF NOT EXISTS idx_crm_leads_utm_campaign
  ON public.crm_leads(utm_campaign);
CREATE INDEX IF NOT EXISTS idx_crm_leads_attribution_session
  ON public.crm_leads(attribution_session_id);

CREATE TABLE IF NOT EXISTS public.marketing_attribution_touches (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id text NOT NULL,
  campaign_id text,
  landing_url text,
  referrer text,
  utm_source text,
  utm_medium text,
  utm_campaign text,
  utm_content text,
  utm_term text,
  gclid text,
  gbraid text,
  wbraid text,
  fbclid text,
  lead_id uuid REFERENCES public.crm_leads(id) ON DELETE SET NULL,
  client_id integer REFERENCES public.clients(id) ON DELETE SET NULL,
  appointment_id uuid REFERENCES public.appointments(id) ON DELETE SET NULL,
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(session_id, utm_source, utm_medium, utm_campaign, utm_content, gclid, fbclid)
);

CREATE INDEX IF NOT EXISTS idx_marketing_touches_campaign
  ON public.marketing_attribution_touches(campaign_id, utm_campaign);
CREATE INDEX IF NOT EXISTS idx_marketing_touches_session
  ON public.marketing_attribution_touches(session_id, last_seen_at DESC);
CREATE INDEX IF NOT EXISTS idx_marketing_touches_lead
  ON public.marketing_attribution_touches(lead_id);

-- Recebe diariamente dados agregados das APIs oficiais ou uma importação auditável.
CREATE TABLE IF NOT EXISTS public.marketing_ad_daily_metrics (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id text,
  metric_date date NOT NULL,
  platform text NOT NULL CHECK (platform IN ('meta_ads', 'google_ads')),
  external_campaign_id text,
  external_campaign_name text,
  external_adset_id text,
  external_ad_id text,
  impressions bigint NOT NULL DEFAULT 0 CHECK (impressions >= 0),
  clicks bigint NOT NULL DEFAULT 0 CHECK (clicks >= 0),
  spend numeric(14,2) NOT NULL DEFAULT 0 CHECK (spend >= 0),
  source_status text NOT NULL DEFAULT 'api' CHECK (source_status IN ('api', 'importado', 'manual')),
  synced_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(platform, metric_date, external_campaign_id, external_adset_id, external_ad_id)
);

CREATE INDEX IF NOT EXISTS idx_marketing_ad_metrics_campaign_date
  ON public.marketing_ad_daily_metrics(campaign_id, metric_date);

ALTER TABLE public.marketing_attribution_touches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.marketing_ad_daily_metrics ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON TABLE public.marketing_attribution_touches TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.marketing_ad_daily_metrics TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.marketing_ad_daily_metrics_id_seq TO authenticated;

