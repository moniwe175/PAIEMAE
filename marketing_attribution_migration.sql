CREATE POLICY marketing_metrics_write_authenticated
  ON public.marketing_ad_daily_metrics FOR ALL TO authenticated USING (true) WITH CHECK (true);

CREATE OR REPLACE FUNCTION public.fn_marketing_capture_touch(
  p_session_id text,
  p_campaign_id text DEFAULT NULL,
  p_landing_url text DEFAULT NULL,
  p_referrer text DEFAULT NULL,
  p_utm_source text DEFAULT NULL,
  p_utm_medium text DEFAULT NULL,
  p_utm_campaign text DEFAULT NULL,
  p_utm_content text DEFAULT NULL,
  p_utm_term text DEFAULT NULL,
  p_gclid text DEFAULT NULL,
  p_gbraid text DEFAULT NULL,
  p_wbraid text DEFAULT NULL,
  p_fbclid text DEFAULT NULL
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_id uuid;
BEGIN
  IF NULLIF(TRIM(p_session_id), '') IS NULL THEN
    RAISE EXCEPTION 'session_id obrigatório';
  END IF;

  SELECT id INTO v_id
  FROM public.marketing_attribution_touches
  WHERE session_id = LEFT(p_session_id, 200)
    AND COALESCE(utm_source, '') = COALESCE(LEFT(p_utm_source, 200), '')
    AND COALESCE(utm_medium, '') = COALESCE(LEFT(p_utm_medium, 200), '')
    AND COALESCE(utm_campaign, '') = COALESCE(LEFT(p_utm_campaign, 200), '')
    AND COALESCE(utm_content, '') = COALESCE(LEFT(p_utm_content, 200), '')
    AND COALESCE(gclid, '') = COALESCE(LEFT(p_gclid, 500), '')
    AND COALESCE(fbclid, '') = COALESCE(LEFT(p_fbclid, 500), '')
  ORDER BY last_seen_at DESC
  LIMIT 1;

  IF v_id IS NOT NULL THEN
    UPDATE public.marketing_attribution_touches
    SET last_seen_at = now(),
        campaign_id = COALESCE(LEFT(p_campaign_id, 200), campaign_id),
        landing_url = COALESCE(LEFT(p_landing_url, 1000), landing_url),
        referrer = COALESCE(LEFT(p_referrer, 1000), referrer)
    WHERE id = v_id;
    RETURN v_id;
  END IF;

  INSERT INTO public.marketing_attribution_touches (
    session_id, campaign_id, landing_url, referrer, utm_source, utm_medium, utm_campaign,
    utm_content, utm_term, gclid, gbraid, wbraid, fbclid
  ) VALUES (
    LEFT(p_session_id, 200), LEFT(p_campaign_id, 200), LEFT(p_landing_url, 1000), LEFT(p_referrer, 1000),
    LEFT(p_utm_source, 200), LEFT(p_utm_medium, 200), LEFT(p_utm_campaign, 200),
    LEFT(p_utm_content, 200), LEFT(p_utm_term, 200), LEFT(p_gclid, 500),
    LEFT(p_gbraid, 500), LEFT(p_wbraid, 500), LEFT(p_fbclid, 500)
  ) RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;

REVOKE ALL ON FUNCTION public.fn_marketing_capture_touch(text,text,text,text,text,text,text,text,text,text,text,text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.fn_marketing_capture_touch(text,text,text,text,text,text,text,text,text,text,text,text,text) TO anon, authenticated;

CREATE OR REPLACE FUNCTION public.fn_marketing_link_touch_to_lead()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NULLIF(TRIM(NEW.attribution_session_id), '') IS NULL THEN RETURN NEW; END IF;

  UPDATE public.marketing_attribution_touches
  SET lead_id = NEW.id,
      client_id = NEW.client_id,
      appointment_id = NEW.appointment_id,
      campaign_id = COALESCE(NEW.marketing_campaign_id, campaign_id),
      last_seen_at = now()
  WHERE id = (
    SELECT id FROM public.marketing_attribution_touches
    WHERE session_id = NEW.attribution_session_id
    ORDER BY last_seen_at DESC LIMIT 1
  );
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_marketing_link_touch_to_lead ON public.crm_leads;
DROP TRIGGER IF EXISTS trg_marketing_link_touch_to_lead_insert ON public.crm_leads;
DROP TRIGGER IF EXISTS trg_marketing_link_touch_to_lead_update ON public.crm_leads;
CREATE TRIGGER trg_marketing_link_touch_to_lead_insert
AFTER INSERT ON public.crm_leads
FOR EACH ROW EXECUTE FUNCTION public.fn_marketing_link_touch_to_lead();
CREATE TRIGGER trg_marketing_link_touch_to_lead_update
AFTER UPDATE OF client_id, appointment_id, marketing_campaign_id ON public.crm_leads
FOR EACH ROW EXECUTE FUNCTION public.fn_marketing_link_touch_to_lead();

-- Métricas comprovadas pelo ERP. Receita só entra quando a transação está
-- conciliada em commercial_record_links; sem conciliação, retorna zero e cobertura.
CREATE OR REPLACE FUNCTION public.fn_marketing_campaign_performance()
RETURNS TABLE (
  campaign_key text,
  leads bigint,
  scheduled bigint,
  attended bigint,
  lost bigint,
  paying_customers bigint,
  revenue numeric,
  linked_financial_records bigint,
  impressions bigint,
  clicks bigint,
  spend numeric,
  ad_data_status text
)
LANGUAGE sql
SECURITY INVOKER
SET search_path = public
AS $$
  WITH lead_base AS (
    SELECT
      l.*,
      COALESCE(NULLIF(l.marketing_campaign_id, ''), NULLIF(l.utm_campaign, '')) AS campaign_key
    FROM public.crm_leads l
    WHERE COALESCE(NULLIF(l.marketing_campaign_id, ''), NULLIF(l.utm_campaign, '')) IS NOT NULL
  ),
  lead_agg AS (
    SELECT
      lb.campaign_key,
      COUNT(DISTINCT lb.id) AS leads,
      COUNT(DISTINCT lb.id) FILTER (
        WHERE lb.appointment_id IS NOT NULL
          AND COALESCE(a.status, '') NOT IN ('cancelado', 'desmarcado', 'falta')
      ) AS scheduled,
      COUNT(DISTINCT lb.id) FILTER (WHERE a.status = 'finalizado') AS attended,
      COUNT(DISTINCT lb.id) FILTER (WHERE lb.status = 'encerrado_perdido') AS lost
    FROM lead_base lb
    LEFT JOIN public.appointments a ON a.id = lb.appointment_id
    GROUP BY lb.campaign_key
  ),
  attributed_finance AS (
    SELECT
      chosen.campaign_key,
      COUNT(DISTINCT crl.source_id) AS linked_financial_records,
      COUNT(DISTINCT crl.client_id) AS paying_customers,
      COALESCE(SUM(st.gross), 0) AS revenue
    FROM public.commercial_record_links crl
    INNER JOIN public.sheet_transactions st
      ON crl.source_table = 'sheet_transactions'
     AND crl.source_id = st.id::text
    INNER JOIN LATERAL (
      SELECT lb.campaign_key
      FROM lead_base lb
      WHERE lb.client_id = crl.client_id
        AND (lb.created_at AT TIME ZONE 'America/Sao_Paulo')::date <= st.date_ref
      ORDER BY lb.created_at DESC
      LIMIT 1
    ) chosen ON true
    WHERE st.deleted_at IS NULL
      AND (st.is_metadata IS NOT TRUE OR st.is_metadata IS NULL)
      AND lower(COALESCE(st.row_type, st.tipo, '')) = 'receita'
    GROUP BY chosen.campaign_key
  ),
  ad_agg AS (
    SELECT
      campaign_id AS campaign_key,
      SUM(impressions)::bigint AS impressions,
      SUM(clicks)::bigint AS clicks,
      SUM(spend)::numeric AS spend,
      CASE
        WHEN BOOL_AND(source_status = 'api') THEN 'api'
        WHEN BOOL_OR(source_status = 'api') THEN 'parcial'
        ELSE MAX(source_status)
      END AS ad_data_status
    FROM public.marketing_ad_daily_metrics
    WHERE campaign_id IS NOT NULL
    GROUP BY campaign_id
  ),
  keys AS (
    SELECT campaign_key FROM lead_agg
    UNION
    SELECT campaign_key FROM ad_agg
  )
  SELECT
    k.campaign_key,
    COALESCE(la.leads, 0), COALESCE(la.scheduled, 0), COALESCE(la.attended, 0),
    COALESCE(la.lost, 0), COALESCE(af.paying_customers, 0),
    COALESCE(af.revenue, 0), COALESCE(af.linked_financial_records, 0),
    COALESCE(aa.impressions, 0), COALESCE(aa.clicks, 0), COALESCE(aa.spend, 0),
    COALESCE(aa.ad_data_status, 'pendente')
  FROM keys k
  LEFT JOIN lead_agg la USING (campaign_key)
  LEFT JOIN attributed_finance af USING (campaign_key)
  LEFT JOIN ad_agg aa USING (campaign_key)
  ORDER BY COALESCE(af.revenue, 0) DESC, COALESCE(la.leads, 0) DESC;
$$;

REVOKE ALL ON FUNCTION public.fn_marketing_campaign_performance() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.fn_marketing_campaign_performance() TO authenticated;

COMMIT;

